#!/usr/bin/env python3
"""Writes the generated sessions of tests/search/clockgames*.sessions: games of
the sample of tests/differential (its lines of play), played on a clock under
`nodestime`, so that bench/compare_uci.py can compare them with the reference
(README.md, "Time management"). Standard library only; deterministic.

    make_clock_sessions.py LINES.gz SEED COUNT > SESSIONS

Each session sets nodestime, Move Overhead and Ponder, then gives the engine a
clock at each of its moves along one line of play: sudden death, increment or
movestogo cycles, from a few milliseconds to minutes, for White, Black or both
sides (as in analysis, where the nodes left are shared), sometimes with a
ucinewgame in the middle (a new game on the same line, which resets the nodes
left). The clock the GUI sends runs down by a fixed share per move: under
nodestime the engine reads it at the first move of a game only, and the
nodes it uses are its own count.
"""

import gzip
import random
import sys


def main():
    path, seed, count = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
    rng = random.Random(seed)
    with gzip.open(path, "rt") as f:
        lines = [line.split() for line in f if line.strip()]

    print(f"# Generated by bench/make_clock_sessions.py {path.split('/')[-1]} {seed} {count}; do not edit.")
    for n in range(count):
        line = lines[n % len(lines)]
        i = line.index("moves") if "moves" in line else len(line)
        head, moves = line[:i], line[i + 1 :]
        if len(moves) < 4:
            continue

        np = rng.choice([10, 20, 50, 100])
        overhead = rng.choice([10, 10, 0, 30, 100])
        ponder = rng.random() < 0.25
        kind = rng.choice(["sudden", "increment", "increment", "cycle"])
        base = rng.choice([30, 100, 300, 1000, 3000, 10000, 30000, 60000])
        inc = 0 if kind == "sudden" else rng.choice([0, 10, 100, 1000])
        cycle = rng.choice([1, 2, 3, 5, 10, 40]) if kind == "cycle" else 0
        side = rng.choice(["white", "black", "both"])
        start = rng.randrange(0, min(20, len(moves) - 2))
        plays = rng.randrange(3, 13)
        newgame_at = rng.randrange(1, plays) if rng.random() < 0.15 else -1

        cmds = [
            f"setoption name nodestime value {np}",
            f"setoption name Move Overhead value {overhead}",
            f"setoption name Ponder value {'true' if ponder else 'false'}",
        ]
        clock = [base, base]
        togo = cycle
        played = 0
        ply = start
        while played < plays and ply < len(moves):
            stm = 0 if (ply % 2 == 0) == (head[0] == "startpos" or " w " in " ".join(head)) else 1
            if side == "both" or (side == "white") == (stm == 0):
                if played == newgame_at:
                    cmds.append("ucinewgame")
                pos = " ".join(head + (["moves"] + moves[:ply] if ply else []))
                go = f"go wtime {clock[0]} btime {clock[1]}"
                if inc:
                    go += f" winc {inc} binc {inc}"
                if cycle:
                    go += f" movestogo {togo}"
                cmds += [f"position {pos}", go]
                played += 1
                # the GUI's clock of the side that moved
                clock[stm] = max(1, clock[stm] - clock[stm] // 25) + inc
                if cycle and stm == 1:
                    togo -= 1
                    if togo == 0:
                        togo = cycle
                        clock = [clock[0] + base, clock[1] + base]
            else:
                clock[stm] = max(1, clock[stm] - clock[stm] // 30) + inc
            ply += 1
        print(" ; ".join(cmds))


if __name__ == "__main__":
    main()
